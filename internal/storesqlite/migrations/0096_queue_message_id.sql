-- 0096_queue_message_id.sql -- adds queue.message_id (issue #235, split
-- from #143's 2026-07-12 alias-forward triage comment).
--
-- Message research's address-based search (sender/recipient substring on
-- mail_from/rcpt_to) cannot find a relay/forward queue row when the row's
-- addresses have been rewritten: an alias with an external forwarding
-- target relays inbound mail onward with SRS return-path rewriting, so
-- the relay row's mail_from is an SRS-encoded address and its rcpt_to is
-- the external target -- neither contains the original sender/recipient
-- address as a substring.
--
-- message_id captures the RFC 5322 Message-ID header of the submitted
-- body at Queue.Submit time, normalised (angle brackets stripped,
-- lowercased) the same way InsertMessage already normalises
-- messages.env_message_id for a received message's envelope. Message
-- research now finds the received message via the operator's address
-- search, reads its Message-ID, and runs a second queue lookup keyed on
-- that value -- an exact join that survives SRS rewriting and fan-out,
-- unlike the address-substring match.
--
-- '' (empty string, the NOT NULL DEFAULT) means "no Message-ID header
-- found on the submitted body" -- every row that predates this migration,
-- and rows from paths whose body has no Message-ID (rare; e.g. a
-- synthetic DSN generated by dsn.go, which passes its own MessageID
-- field through a separate mechanism, not through Submit's body).
--
-- The partial index only covers non-empty values: the column is empty on
-- most historical rows and every DSN/bounce row, so indexing '' would
-- bloat the index for no query benefit (every message-research lookup
-- supplies a specific, non-empty Message-ID).
--
-- No new table; QueueRow gains the one field. Forward-only.

ALTER TABLE queue ADD COLUMN message_id TEXT NOT NULL DEFAULT '';
CREATE INDEX idx_queue_message_id ON queue(message_id) WHERE message_id <> '';
